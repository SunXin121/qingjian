// 多维表格 (bitable). A table is a node of type "table" with its own fields, views and
// records. Records store raw values in a JSON object keyed by field id; filtering,
// sorting, grouping and formulas all run in the browser, the server only persists.

type Field struct {
	ID      string          `json:"id"`
	Name    string          `json:"name"`
	Type    string          `json:"type"`
	Options json.RawMessage `json:"options"`
	Sort    float64         `json:"sort"`
}

type View struct {
	ID     string          `json:"id"`
	Name   string          `json:"name"`
	Type   string          `json:"type"`
	Config json.RawMessage `json:"config"`
	Sort   float64         `json:"sort"`
}

type Record struct {
	ID        string          `json:"id"`
	Seq       int64           `json:"seq"`
	Data      json.RawMessage `json:"data"`
	Sort      float64         `json:"sort"`
	CreatedAt int64           `json:"created_at"`
	UpdatedAt int64           `json:"updated_at"`
}

type TableData struct {
	Node
	Fields  []Field  `json:"fields"`
	Views   []View   `json:"views"`
	Records []Record `json:"records"`
}

var (
	fieldTypes = map[string]bool{
		"text": true, "longtext": true, "number": true, "select": true, "multiselect": true, "date": true,
		"checkbox": true, "url": true, "attachment": true, "autonumber": true, "created_time": true, "modified_time": true,
		"rating": true, "progress": true, "phone": true, "email": true,
	}
	viewTypes = map[string]bool{"grid": true, "kanban": true}
	// ids of fields / views / records are generated by the client so edits can be applied
	// optimistically; they double as JSON object keys and json paths, so keep them plain.
	reBTID = regexp.MustCompile(`^[0-9a-z]{6,32}$`)
)

const maxTableOps = 20000

type querier interface {
	QueryRow(string, ...any) *sql.Row
	Query(string, ...any) (*sql.Rows, error)
}

// loadTableData returns the table node with everything in it.
func (s *Server) loadTableData(q querier, id string) (*TableData, error) {
	n, err := s.loadNode(q, id)
	if err != nil {
		return nil, err
	}
	if n.Type != "table" {
		return nil, sql.ErrNoRows
	}
	t := &TableData{Node: *n, Fields: []Field{}, Views: []View{}, Records: []Record{}}
	rows, err := q.Query(`SELECT id, name, type, options, sort FROM bt_fields WHERE table_node_id = ? ORDER BY sort, rowid`, id)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var f Field
		var opts string
		if err := rows.Scan(&f.ID, &f.Name, &f.Type, &opts, &f.Sort); err != nil {
			rows.Close()
			return nil, err
		}
		f.Options = json.RawMessage(opts)
		t.Fields = append(t.Fields, f)
	}
	rows.Close()
	rows, err = q.Query(`SELECT id, name, type, config, sort FROM bt_views WHERE table_node_id = ? ORDER BY sort, rowid`, id)
	if err != nil {
		return nil, err
	}
	for rows.Next() {
		var v View
		var cfg string
		if err := rows.Scan(&v.ID, &v.Name, &v.Type, &cfg, &v.Sort); err != nil {
			rows.Close()
			return nil, err
		}
		v.Config = json.RawMessage(cfg)
		t.Views = append(t.Views, v)
	}
	rows.Close()
	rows, err = q.Query(`SELECT id, seq, data, sort, created_at, updated_at FROM bt_records WHERE table_node_id = ? ORDER BY sort, seq`, id)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	for rows.Next() {
		var r Record
		var data string
		if err := rows.Scan(&r.ID, &r.Seq, &data, &r.Sort, &r.CreatedAt, &r.UpdatedAt); err != nil {
			return nil, err
		}
		r.Data = json.RawMessage(data)
		t.Records = append(t.Records, r)
	}
	return t, rows.Err()
}

// initTable fills a freshly created table with a starter layout.
func initTable(tx *sql.Tx, tableID string, t int64) error {
	choices, _ := json.Marshal(map[string]any{"choices": []map[string]any{
		{"id": newID(), "name": "待开始", "color": 0},
		{"id": newID(), "name": "进行中", "color": 1},
		{"id": newID(), "name": "已完成", "color": 2},
	}})
	fields := []Field{
		{ID: newID(), Name: "名称", Type: "text", Options: json.RawMessage(`{}`), Sort: 1},
		{ID: newID(), Name: "状态", Type: "select", Options: choices, Sort: 2},
		{ID: newID(), Name: "日期", Type: "date", Options: json.RawMessage(`{}`), Sort: 3},
	}
	for _, f := range fields {
		if _, err := tx.Exec(`INSERT INTO bt_fields(id, table_node_id, name, type, options, sort) VALUES(?,?,?,?,?,?)`,
			f.ID, tableID, f.Name, f.Type, string(f.Options), f.Sort); err != nil {
			return err
		}
	}
	if _, err := tx.Exec(`INSERT INTO bt_views(id, table_node_id, name, type, config, sort) VALUES(?,?,?,?,?,?)`,
		newID(), tableID, "表格视图", "grid", `{}`, 1); err != nil {
		return err
	}
	for i := 1; i <= 3; i++ {
		if _, err := tx.Exec(`INSERT INTO bt_records(id, table_node_id, seq, data, sort, created_at, updated_at) VALUES(?,?,?,?,?,?,?)`,
			newID(), tableID, i, `{}`, i, t, t); err != nil {
			return err
		}
	}
	return nil
}

func (s *Server) getTable(w http.ResponseWriter, r *http.Request) {
	t, err := s.loadTableData(s.db, r.PathValue("id"))
	if errors.Is(err, sql.ErrNoRows) {
		httpError(w, 404, "表格不存在")
		return
	} else if err != nil {
		httpError(w, 500, err.Error())
		return
	}
	writeJSON(w, 200, t)
}

type tableSummary struct {
	ID       string        `json:"id"`
	Title    string        `json:"title"`
	RepoID   string        `json:"repo_id"`
	RepoName string        `json:"repo_name"`
	Views    []viewSummary `json:"views"`
}

type viewSummary struct {
	ID   string `json:"id"`
	Name string `json:"name"`
	Type string `json:"type"`
}

// listTables powers the "embed a table" picker in the editor.
func (s *Server) listTables(w http.ResponseWriter, r *http.Request) {
	rows, err := s.db.Query(`SELECT n.id, n.title, n.repo_id, r.name FROM nodes n JOIN repos r ON r.id = n.repo_id
WHERE n.type = 'table' AND n.deleted_at IS NULL AND r.deleted_at IS NULL ORDER BY n.updated_at DESC`)
	if err != nil {
		httpError(w, 500, err.Error())
		return
	}
	out := []*tableSummary{}
	byID := map[string]*tableSummary{}
	for rows.Next() {
		t := &tableSummary{Views: []viewSummary{}}
		rows.Scan(&t.ID, &t.Title, &t.RepoID, &t.RepoName)
		out = append(out, t)
		byID[t.ID] = t
	}
	rows.Close()
	rows, err = s.db.Query(`SELECT table_node_id, id, name, type FROM bt_views ORDER BY sort, rowid`)
	if err != nil {
		httpError(w, 500, err.Error())
		return
	}
	defer rows.Close()
	for rows.Next() {
		var tid string
		var v viewSummary
		rows.Scan(&tid, &v.ID, &v.Name, &v.Type)
		if t := byID[tid]; t != nil {
			t.Views = append(t.Views, v)
		}
	}
	writeJSON(w, 200, out)
}

// tableOp is one change to a table. Ops are applied in order inside one transaction.
//
//	field.create {id, name, type, options, sort}   field.update {id, name?, type?, options?, sort?}
//	view.create  {id, name, type, config, sort}    view.update  {id, name?, config?, sort?}
//	record.create {id, data, sort, seq?, created_at?}
//	record.update {id, data? (merge patch: null removes a value), sort?}
//	field.delete / view.delete / record.delete {id}
type tableOp struct {
	Op        string          `json:"op"`
	ID        string          `json:"id"`
	Name      *string         `json:"name"`
	Type      *string         `json:"type"`
	Options   json.RawMessage `json:"options"`
	Config    json.RawMessage `json:"config"`
	Sort      *float64        `json:"sort"`
	Data      json.RawMessage `json:"data"`
	Seq       *int64          `json:"seq"`
	CreatedAt *int64          `json:"created_at"`
}

func isJSONObject(raw json.RawMessage) bool {
	t := strings.TrimSpace(string(raw))
	return strings.HasPrefix(t, "{") && json.Valid(raw)
}

func jsonOr(raw json.RawMessage, def string) string {
	if len(raw) == 0 || string(raw) == "null" {
		return def
	}
	return string(raw)
}

type opError struct{ msg string }

func (e opError) Error() string { return e.msg }

func applyTableOp(tx *sql.Tx, tableID string, op tableOp, t int64, h *historyWriter) error {
	if !reBTID.MatchString(op.ID) {
		return opError{"无效的 ID"}
	}
	str := func(p *string) string {
		if p == nil {
			return ""
		}
		return strings.TrimSpace(*p)
	}
	sort := func() float64 {
		if op.Sort == nil {
			return 0
		}
		return *op.Sort
	}
	var err error
	if strings.HasPrefix(op.Op, "field.") {
		h.invalidateFields()
	}
	switch op.Op {
	case "field.create":
		if op.Type == nil || !fieldTypes[*op.Type] {
			return opError{"不支持的字段类型"}
		}
		if op.Options != nil && !isJSONObject(op.Options) && string(op.Options) != "null" {
			return opError{"字段配置格式错误"}
		}
		_, err = tx.Exec(`INSERT INTO bt_fields(id, table_node_id, name, type, options, sort) VALUES(?,?,?,?,?,?)`,
			op.ID, tableID, nonEmpty(str(op.Name), "字段"), *op.Type, jsonOr(op.Options, "{}"), sort())
	case "field.update":
		sets, args := []string{}, []any{}
		if op.Name != nil && str(op.Name) != "" {
			sets, args = append(sets, "name = ?"), append(args, str(op.Name))
		}
		if op.Type != nil {
			if !fieldTypes[*op.Type] {
				return opError{"不支持的字段类型"}
			}
			sets, args = append(sets, "type = ?"), append(args, *op.Type)
		}
		if len(op.Options) > 0 {
			if !isJSONObject(op.Options) {
				return opError{"字段配置格式错误"}
			}
			sets, args = append(sets, "options = ?"), append(args, string(op.Options))
		}
		if op.Sort != nil {
			sets, args = append(sets, "sort = ?"), append(args, *op.Sort)
		}
		if len(sets) > 0 {
			_, err = tx.Exec(`UPDATE bt_fields SET `+strings.Join(sets, ", ")+` WHERE id = ? AND table_node_id = ?`, append(args, op.ID, tableID)...)
		}
	case "field.delete":
		var n int
		tx.QueryRow(`SELECT COUNT(*) FROM bt_fields WHERE table_node_id = ?`, tableID).Scan(&n)
		var primary string
		tx.QueryRow(`SELECT id FROM bt_fields WHERE table_node_id = ? ORDER BY sort, rowid LIMIT 1`, tableID).Scan(&primary)
		if primary == op.ID || n <= 1 {
			return opError{"不能删除主字段"}
		}
		if _, err = tx.Exec(`DELETE FROM bt_fields WHERE id = ? AND table_node_id = ?`, op.ID, tableID); err == nil {
			_, err = tx.Exec(`UPDATE bt_records SET data = json_remove(data, ?) WHERE table_node_id = ?`, `$."`+op.ID+`"`, tableID)
		}
	case "view.create":
		if op.Type == nil || !viewTypes[*op.Type] {
			return opError{"不支持的视图类型"}
		}
		if op.Config != nil && !isJSONObject(op.Config) && string(op.Config) != "null" {
			return opError{"视图配置格式错误"}
		}
		_, err = tx.Exec(`INSERT INTO bt_views(id, table_node_id, name, type, config, sort) VALUES(?,?,?,?,?,?)`,
			op.ID, tableID, nonEmpty(str(op.Name), "视图"), *op.Type, jsonOr(op.Config, "{}"), sort())
	case "view.update":
		sets, args := []string{}, []any{}
		if op.Name != nil && str(op.Name) != "" {
			sets, args = append(sets, "name = ?"), append(args, str(op.Name))
		}
		if len(op.Config) > 0 {
			if !isJSONObject(op.Config) {
				return opError{"视图配置格式错误"}
			}
			sets, args = append(sets, "config = ?"), append(args, string(op.Config))
		}
		if op.Sort != nil {
			sets, args = append(sets, "sort = ?"), append(args, *op.Sort)
		}
		if len(sets) > 0 {
			_, err = tx.Exec(`UPDATE bt_views SET `+strings.Join(sets, ", ")+` WHERE id = ? AND table_node_id = ?`, append(args, op.ID, tableID)...)
		}
	case "view.delete":
		var n int
		tx.QueryRow(`SELECT COUNT(*) FROM bt_views WHERE table_node_id = ?`, tableID).Scan(&n)
		if n <= 1 {
			return opError{"至少需要保留一个视图"}
		}
		_, err = tx.Exec(`DELETE FROM bt_views WHERE id = ? AND table_node_id = ?`, op.ID, tableID)
	case "record.create":
		data := jsonOr(op.Data, "{}")
		if !isJSONObject(json.RawMessage(data)) {
			return opError{"记录格式错误"}
		}
		var seq int64
		if op.Seq != nil && *op.Seq > 0 {
			seq = *op.Seq
		} else {
			tx.QueryRow(`SELECT COALESCE(MAX(seq), 0) + 1 FROM bt_records WHERE table_node_id = ?`, tableID).Scan(&seq)
		}
		created := t
		if op.CreatedAt != nil && *op.CreatedAt > 0 && *op.CreatedAt <= t {
			created = *op.CreatedAt
		}
		_, err = tx.Exec(`INSERT INTO bt_records(id, table_node_id, seq, data, sort, created_at, updated_at) VALUES(?,?,?,?,?,?,?)`,
			op.ID, tableID, seq, data, sort(), created, t)
		if err == nil {
			err = h.logCreate(op.ID, data)
		}
	case "record.update":
		// a patch that changes nothing, or a move (sort only), is not a modification
		sets, args := []string{}, []any{}
		var changes []historyChange
		if len(op.Data) > 0 {
			if !isJSONObject(op.Data) {
				return opError{"记录格式错误"}
			}
			if changes, _, err = h.updateChanges(op.ID, op.Data); err != nil {
				return err
			}
			if len(changes) > 0 {
				// RFC 7396 merge patch; values are scalars or arrays, so it is a per-field set/unset
				sets, args = append(sets, "data = json_patch(data, ?)", "updated_at = ?"), append(args, string(op.Data), t)
			}
		}
		if op.Sort != nil {
			sets, args = append(sets, "sort = ?"), append(args, *op.Sort)
		}
		if len(sets) > 0 {
			_, err = tx.Exec(`UPDATE bt_records SET `+strings.Join(sets, ", ")+` WHERE id = ? AND table_node_id = ?`, append(args, op.ID, tableID)...)
		}
		if err == nil {
			err = h.logUpdate(op.ID, changes)
		}
	case "record.delete":
		var res sql.Result
		if res, err = tx.Exec(`DELETE FROM bt_records WHERE id = ? AND table_node_id = ?`, op.ID, tableID); err == nil {
			if n, _ := res.RowsAffected(); n > 0 {
				err = h.logDelete(op.ID)
			}
		}
	default:
		return opError{"未知操作：" + op.Op}
	}
	if err != nil && strings.Contains(err.Error(), "UNIQUE") {
		return opError{"ID 冲突，请刷新后重试"}
	}
	return err
}

func (s *Server) tableOps(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	var in struct {
		Ops []tableOp `json:"ops"`
	}
	if err := readJSON(r, &in); err != nil {
		httpError(w, 400, "请求格式错误")
		return
	}
	if len(in.Ops) > maxTableOps {
		httpError(w, 400, fmt.Sprintf("单次最多 %d 项修改", maxTableOps))
		return
	}
	tx, err := s.db.Begin()
	if err != nil {
		httpError(w, 500, err.Error())
		return
	}
	defer tx.Rollback()
	n, err := s.loadNode(tx, id)
	if err != nil || n.Type != "table" {
		httpError(w, 404, "表格不存在")
		return
	}
	t := now()
	h := &historyWriter{tx: tx, tableID: id, t: t}
	for i, op := range in.Ops {
		if err := applyTableOp(tx, id, op, t, h); err != nil {
			var oe opError
			if errors.As(err, &oe) {
				httpError(w, 400, oe.msg)
			} else {
				httpError(w, 500, fmt.Sprintf("op %d: %v", i, err))
			}
			return
		}
	}
	tx.Exec(`UPDATE nodes SET updated_at = ? WHERE id = ?`, t, id)
	tx.Exec(`UPDATE repos SET updated_at = ? WHERE id = ?`, t, n.RepoID)
	if err := tx.Commit(); err != nil {
		httpError(w, 500, err.Error())
		return
	}
	writeJSON(w, 200, map[string]any{"updated_at": t})
}
